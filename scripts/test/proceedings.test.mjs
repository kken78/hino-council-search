test("発言索引の年別分割：書いて読むと同じ配列・同じ並び", () => {
  const dir = mkdtempSync(join(tmpdir(), "hino-index-"));
  try {
    const index = [
      { sid: "b_1", year: 2026, text: "新" }, { sid: "b_2", year: 2026, text: "新2" },
      { sid: "a_1", year: 2025, text: "旧" }, { sid: "x_1", year: null, text: "年不明" },
    ];
    const m = writeIndex(dir, index);
    assert.deepEqual(m.shards.map((s) => [s.year, s.count]), [[2026, 2], [2025, 1], [null, 1]]);
    assert.deepEqual(readIndex(dir), index);
    assert.equal(existsSync(join(dir, "index.json")), false);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
