// 審議構造の解析器（scripts/lib/proceedings.mjs）と関連処理の回帰テスト。
// 実行: npm test（node --test）。会議録で実際に見られた言い回しを小さな例にしている。
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, rmSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseDay, expandBills } from "../lib/proceedings.mjs";
import { stripPageHeads, splitSpeeches } from "../lib/speech.mjs";
import { readIndex, writeIndex } from "../lib/data.mjs";

// 発言列を作る小道具：["議長","杉浦和人","…"] の並び → parseDay の入力
const day = (rows, mid = "0000000001", date = "20260101") =>
  rows.map(([role, name, text], i) => ({ i, sid: `${mid}_${date}_${String(i).padStart(4, "0")}`, role, name, text }));
const kinds = (segs) => segs.map((s) => s.kind);

test("expandBills：範囲・列挙・除外・日程番号を挟む範囲", () => {
  assert.deepEqual(expandBills("議第100号から議第103号まで"), ["議第100号", "議第101号", "議第102号", "議第103号"]);
  assert.deepEqual(expandBills("議第１０５号、議第１０９号および議第１１５号"), ["議第105号", "議第109号", "議第115号"]);
  assert.deepEqual(
    expandBills("議第105号および議第109号を除く議第104号から議第110号まで"),
    ["議第104号", "議第106号", "議第107号", "議第108号", "議第110号"],
  );
  assert.deepEqual(expandBills("日程第３ 議第95号から日程第５ 議第97号まで"), ["議第95号", "議第96号", "議第97号"]);
  // 「議第71号の修正議決をした部分を除く部分」は除外ではない
  assert.deepEqual(expandBills("議第71号、補正予算（第３号）の修正議決をした部分を除く部分"), ["議第71号"]);
  assert.deepEqual(expandBills("請願第８号および決議案第２号"), ["請願第8号", "決議案第2号"]);
});

test("stripPageHeads：行位置どおりのページ番号だけを除去（議席番号を巻き込まない）", () => {
  const raw = "2-1日野町議会\n2-2ます。\n2-310番（加藤和幸君） 質問します。";
  const out = stripPageHeads(raw);
  assert.equal(out, "日野町議会\nます。\n10番（加藤和幸君） 質問します。");
  assert.equal(splitSpeeches(out).at(-1).role, "10番");
  // 期待どおりでない行があれば無変更
  assert.equal(stripPageHeads("目 次\n１．議第１号"), "目 次\n１．議第１号");
});

test("一般質問：質問・答弁・再質問・新しい問、質問方式と質問項目", () => {
  const segs = parseDay(day([
    ["議長", "杉浦和人", "日程第１ 一般質問を行います。通告に基づき、順次発言を許可いたします。３番、谷口智哉君。"],
    ["3番", "谷口智哉", "一問一答にて大きく２問質問します。まず１問目、チョイソコひのについて伺います。"],
    ["議長", "杉浦和人", "３番、谷口智哉君の質問に対する当局の答弁を求めます。町長。"],
    ["町長", "堀江和博", "ただいま、チョイソコひのについてご質問を頂きました。"],
    ["議長", "杉浦和人", "谷口智哉君。"],
    ["3番", "谷口智哉", "再質問させていただきます。"],
    ["議長", "杉浦和人", "交通環境政策課長。"],
    ["交通環境政策課長", "小島勝", "お答えします。"],
    ["議長", "杉浦和人", "谷口智哉君。"],
    ["3番", "谷口智哉", "次に、２問目の質問です。体験格差について伺います。"],
    ["議長", "杉浦和人", "教育長。"],
    ["教育長", "安田寛次", "体験格差の解消に向けた取組についてご質問いただきました。"],
    ["議長", "杉浦和人", "次に、６番、川東昭男君。"],
    ["6番", "川東昭男", "分割方式で質問します。"],
  ]));
  assert.deepEqual(kinds(segs), ["ippan", "ippan"]);
  const [a, b] = segs;
  assert.equal(a.member, "谷口智哉");
  assert.equal(a.style, "一問一答");
  assert.deepEqual(a.turns.map(([, t, n]) => t + n), ["q1", "a1", "rq1", "a1", "q2", "a2"]);
  assert.deepEqual(a.topics.map((t) => t.title), ["チョイソコひの", "体験格差の解消に向けた取組"]);
  assert.equal(b.member, "川東昭男");
  assert.equal(b.style, "分割");
});

